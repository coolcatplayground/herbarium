import manifest from "./plates.json";

// The curator's own specimen plates, and the rule for when to use one.
//
// Each is an illustration of the botanical part a specimen is built on — the
// bulb, the pitcher, the seed head — rather than of the creature. That is the
// project's whole argument made visible: a drawing of Bulbasaur is a drawing of
// Bulbasaur, but a drawing of the bulb is a drawing of a corm, which is what
// the field note says it is. It also means the site stops redistributing
// artwork it does not own.
//
// The set arrives one plate at a time. `hasPlate` is what keeps that from being
// a half-finished-looking site: where a plate exists it is shown, and where one
// does not the sprite stands in, with no gap and no broken image between them.
//
// The manifest is generated by scripts/index-plates.mjs and imported rather
// than fetched, so the answer is synchronous and a specimen without a plate
// never costs a request.

export function hasPlate(name) {
  return typeof name === "string" && Object.hasOwn(manifest, name.toLowerCase());
}

export function plateUrl(name) {
  if (!hasPlate(name)) return null;
  return `${import.meta.env.BASE_URL}plates/${manifest[name.toLowerCase()]}`;
}

// How far through the set the collection is. The Curator's Note can say so
// honestly while it is in progress, rather than quietly looking incomplete.
export function plateCount() {
  return Object.keys(manifest).length;
}
